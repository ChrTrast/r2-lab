"""Τα 10 σχέδια (οι στόχοι) των Κύβων, από το πιο εύκολο στο πιο δύσκολο.

Κάθε σχέδιο έχει:
  palette: οι κύβοι που παίρνει το παιδί
  columns: οι στήλες του στόχου, από κάτω προς τα πάνω
(1-4 μπλε/κόκκινος/πράσινος/κίτρινος, 5 διάφανος, 6-9 δίχρωμοι, 10-16 οι μισοί.)
Ό,τι χτίζει το παιδί στο ελεύθερο παιχνίδι δεν αποθηκεύεται.
"""
import random
from dataclasses import dataclass

# Κάθε σχέδιο φέρνει κάτι λίγο πιο δύσκολο.
FIRST = [
    # 1. Σκαλίτσα: ολόκληροι κύβοι, δύο χρώματα, ένα σκαλί σε κάθε στήλη.
    ([3, 2, 1, 4, 5],
     [[2], [3, 2], [3, 3, 2], [3, 3, 3, 2]]),
    # 2. Πόλη: τρεις πολυκατοικίες με μπλε παράθυρα. Μετράει η σειρά των κύβων μέσα στη στήλη.
    ([2, 1, 4, 3, 5],
     [[2, 1, 2], [2, 1, 2], [4, 1, 4, 1, 4], [4, 1, 4, 1, 4], [3, 3, 1, 3], [3, 3, 1, 3]]),
    # 3. Μανιτάρι: πρώτη φορά οι διάφανοι κύβοι, για να «αιωρείται» το καπέλο πάνω από το έδαφος.
    ([4, 2, 5, 3, 1],
     [[5, 5, 2], [5, 5, 2, 2], [4, 4, 2, 2, 2], [5, 5, 2, 2], [5, 5, 2]]),
    # 4. Ρομπότ: κενό ανάμεσα στα πόδια, χέρια στον αέρα, κεραία.
    ([1, 2, 3, 4, 5],
     [[5, 5, 5, 4], [1, 1, 2, 2, 2, 3, 3], [5, 5, 2, 2, 2, 3, 3, 4], [1, 1, 2, 2, 2, 3, 3], [5, 5, 5, 4]]),
    # 5. Τούρτα: πρώτη φορά οι μισοί κύβοι (κρέμα, γλάσο, φλόγες των κεριών).
    ([4, 11, 10, 2, 13],
     [[4, 11, 4, 10], [4, 11, 4, 10, 2, 13], [4, 11, 4, 10], [4, 11, 4, 10], [4, 11, 4, 10, 2, 13],
      [4, 11, 4, 10]]),
    # 6. Πύραυλος: διάφανοι και μισοί μαζί (πτερύγια στον αέρα, φωτιά, μύτη και αστέρια από μισούς κύβους).
    ([1, 2, 3, 13, 11, 5],
     [[5, 5, 5, 13], [], [5, 2, 2], [13, 13, 1, 1, 3, 1, 11], [5, 2, 2], [], [5, 5, 13]]),
]

NEW = [
    # 7. Αυτοκίνητο: ολόκληροι κύβοι και κενά (ρόδες, παράθυρα).
    ([2, 1, 4, 3, 5],
     [[5, 2], [1, 2], [5, 2, 2, 2], [5, 2, 5, 2], [5, 2, 2, 2], [5, 2, 5, 2], [1, 2], [5, 4]]),
    # 8. Χαρταετός: πρώτη φορά οι δίχρωμοι κύβοι, όλοι οι 4 (ένας για κάθε πλευρά του ρόμβου).
    ([2, 1, 6, 7, 8, 9, 4, 3, 5],
     [[5, 5, 5, 5, 1, 9, 6, 1], [5, 5, 3, 5, 9, 2, 2, 6], [5, 4, 5, 4, 8, 2, 2, 7], [5, 5, 5, 5, 1, 8, 7, 1]]),
    # 9. Ψαράκι στη θάλασσα: δίχρωμοι για την ουρά και το κεφάλι, φύκια και άμμος.
    ([1, 2, 3, 4, 6, 7, 8, 9],
     [[4, 3, 3, 1, 1], [4, 1, 8, 7, 1], [4, 1, 9, 6, 1], [4, 1, 2, 2, 1], [4, 1, 2, 4, 1], [4, 1, 8, 7, 1],
      [4, 3, 3, 3, 1]]),
    # 10. Κάστρο: όλα μαζί. Κενό για την πύλη, δίχρωμοι για τις σκεπές, μισοί κύβοι για τις επάλξεις.
    ([4, 1, 2, 6, 7, 13, 5],
     [[4, 4, 4, 4, 4, 4, 6], [4, 4, 4, 4, 1, 4, 7], [4, 4, 4, 4, 13], [5, 5, 4, 4], [4, 4, 4, 4, 13],
      [4, 4, 4, 4, 1, 4, 6], [4, 4, 4, 4, 4, 4, 7]]),
]


@dataclass
class Pattern:
    palette: list
    columns: list


BUILT_IN = [Pattern(list(p), [list(c) for c in cols]) for p, cols in FIRST + NEW]


def cubes_for(pattern, seed):
    """Οι κύβοι του δίσκου. Αν είναι λιγότεροι από 5, μπαίνουν και τυχαίοι, για να έχει επιλογές το παιδί."""
    palette = list(dict.fromkeys(pattern.palette))[:9]
    rng = random.Random(seed)
    while len(palette) < 5:
        ctype = rng.randint(1, 16)
        if ctype not in palette:
            palette.append(ctype)
    return palette
