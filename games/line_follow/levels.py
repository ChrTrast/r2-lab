def _river(col, bridges):
    """Ποτάμι σε όλη τη στήλη col, με ξύλινες γέφυρες (σταθερά οριζόντια κομμάτια) στις σειρές bridges."""
    return tuple((col, r) for r in range(4)), tuple(((col, r), 6) for r in bridges)


