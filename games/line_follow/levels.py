"""Οι 15 πίστες του «Ακολούθησε».

pieces:  πόσα κομμάτια από κάθε τύπο 1-6 παίρνει το παιδί
         (1 ┐ αριστερά-κάτω, 2 ┘ αριστερά-πάνω, 3 └ πάνω-δεξιά,
          4 ┌ κάτω-δεξιά, 5 │ πάνω-κάτω, 6 ─ αριστερά-δεξιά)
blocked: κελιά (στήλη, σειρά) με δέντρο, σπίτι ή βράχους. Η στήλη 0 είναι αριστερά, δίπλα στον φορτιστή,
         και η σειρά 0 είναι η πιο πίσω. Το R2 μπαίνει στο κελί (4, 2) και βγαίνει από το (0, 1).
mode:    0 = το R2 ξεκινά μόνο όταν η γραμμή είναι έτοιμη
         1 = το παιδί στέλνει το R2 όποτε θέλει, για να δοκιμάσει
kinds:   τι στέκεται σε κάθε κελί του blocked, με την ίδια σειρά (αλλιώς διαλέγεται τυχαία)
hint:    το μήνυμα στην αρχή της πίστας

Οι πίστες 12-15 έχουν επιπλέον:
water:   κελιά με νερό (ποτάμι)
fixed:   σταθερά κομμάτια (κελί, κομμάτι): στο νερό είναι γέφυρες, το 7 είναι διασταύρωση
gears:   κελιά με γρανάζι: η μπάρα του φορτιστή ανοίγει όταν τα μαζέψει όλα το R2
"""
from dataclasses import dataclass

from .logic import Board


@dataclass(frozen=True)
class Level:
    pieces: tuple
    blocked: tuple
    mode: int
    kinds: tuple = ()
    water: tuple = ()
    fixed: tuple = ()
    gears: tuple = ()
    hint: str = ""

    @property
    def special(self):
        """Οι πίστες 12-15, με γρανάζια, ποτάμι ή διασταύρωση."""
        return bool(self.water or self.fixed or self.gears)

    @property
    def closed(self):
        """Κελιά όπου δεν μπαίνει κομμάτι: δέντρα, σπίτια, βράχοι και νερό χωρίς γέφυρα."""
        bridges = {cell for cell, _ in self.fixed}
        return tuple(sorted(set(self.blocked) | (set(self.water) - bridges)))

    def board(self):
        return Board(self.closed, self.fixed, self.gears)

    def solve_args(self):
        return self.pieces, self.closed, self.fixed, self.gears


