"""Οι 20 πίστες του «Προγραμμάτισε».

Κάθε πίστα είναι ένα λεξικό:
    mode     "see": οδηγείς με κουμπιά και το πρόγραμμα γράφεται μόνο του,
             "fix": έτοιμο πρόγραμμα με ένα λάθος, "write": το γράφεις όλο
    title    η οδηγία πάνω πάνω
    maps     ο χάρτης (ή πολλοί: τότε αλλάζει σε κάθε «Πάμε» και το πρόγραμμα πρέπει να πετύχει σε όλους.
             Τώρα όλες οι πίστες έχουν έναν χάρτη, για να μη μπερδεύονται τα παιδιά)
    face     προς τα πού κοιτάει το R2 στην αρχή ("right", "down", "left", "up")
    bug      η διαδρομή της πασχαλίτσας (πηγαινοέρχεται 1 κουτάκι το δευτερόλεπτο)
    sink     οι γέφυρες «=» βουλιάζουν: (δευτερόλεπτα πάνω, κάτω, πόσα έχουν περάσει στο «Πάμε»)
    line     η μαύρη γραμμή: τα κουτάκια της με τη σειρά, από την αρχή της (για το «Ακολούθησε τη μαύρη γραμμή»)
    keys     τηλεκοντρόλ: προγράμματα «όταν πατηθεί πλήκτρο» που τα τρέχουν τα κουμπιά του χειριστηρίου
             (program: τα έτοιμα, drive: πατήματα για τους ελέγχους)
    mover    μια εργαλειοθήκη που προχωρά 1 κουτάκι το δευτερόλεπτο σε αυτά τα κουτάκια και μένει στο τελευταίο
    palette  οι εντολές που μπορεί να σύρει το παιδί (οι «Διόρθωσε» δεν έχουν: εκεί τα μπλοκ μένουν στη θέση τους)
    program  το έτοιμο πρόγραμμα των πιστών «Διόρθωσε»
    limit    για το 3ο αστέρι: ως τόσες εντολές
    solution μια σωστή λύση (δεν φαίνεται: την ελέγχουν τα tests)

Ο χάρτης, με κενά ανάμεσα στους χαρακτήρες:
    .  χορτάρι      S  αρχή          G  φορτιστής       c  κρύσταλλος
    #  πέτρα        T  δέντρο        ~  νερό            =  ξύλινη γέφυρα     s  αμμουδιά
    R  B  Y  P      πόρτα κόκκινη, μπλε, κίτρινη, πράσινη (ανοίγει όταν το LED έχει το χρώμα της)
Πέτρες, δέντρα και κλειστές πόρτες τα «βλέπει» ο αισθητήρας απόστασης· το νερό όχι.
"""
from .logic import follow, forever, go, if_else, key, led, move, repeat, stop, turn, until, wait

MOVE_TURN = [move("forward", 1), turn("right", 1)]

LEVELS = [
    # ------------------------------------------------- Α'-Β'. «Δες»: κίνηση, μία στροφή, πίσω
    dict(mode="see", title="Οδήγησε το R2 στον φορτιστή. Το πρόγραμμα γράφεται μόνο του!",
         maps=["""
         T . . . T
         S . c . G
         . . . . .
         """], limit=1, solution=[move("forward", 4)]),

    dict(mode="see", title="Πάρε τους κρυστάλλους και πήγαινε στον φορτιστή!",
         maps=["""
         . . . T .
         S c . ~ T
         ~ ~ . ~ ~
         T ~ c ~ .
         . ~ G ~ .
         """], limit=3,
         solution=[move("forward", 2), turn("right"), move("forward", 3)]),

    dict(mode="see", title="Ο κρύσταλλος είναι σε αδιέξοδο! Μετά γύρνα με το κουμπί «Πίσω».",
         maps=["""
         T . . . . T
         S . . c ~ T
         ~ ~ . ~ ~ ~
         . . . . G .
         """], limit=6,
         solution=[move("forward", 3), move("back", 1), turn("right"), move("forward", 2), turn("left"),
                   move("forward", 2)]),

    # ------------------------------------------------- «Διόρθωσε», το πρώτο «Γράψε» και το «περίμενε»
    # Οι «Διόρθωσε» δεν έχουν Εντολές: το παιδί αλλάζει μόνο ▾, αριθμούς και χρώματα, δεν προσθέτει μπλοκ.
    dict(mode="fix", title="Το R2 σταμάτησε πριν τον φορτιστή! Διόρθωσε έναν αριθμό.",
         maps=["""
         . . . . . T
         S . c . . .
         ~ ~ ~ ~ . ~
         T . . . G .
         """],
         program=[move("forward", 4), turn("right"), move("forward", 1)], limit=3,
         solution=[move("forward", 4), turn("right"), move("forward", 2)]),

    dict(mode="fix", title="Το R2 μπερδεύτηκε! Βρες τη λάθος στροφή και διόρθωσέ τη.",
         maps=["""
         . . . . G T
         T . ~ ~ c .
         S . c . . ~
         . . ~ ~ ~ .
         """],
         program=[move("forward", 4), turn("right"), move("forward", 2)], limit=3,
         solution=[move("forward", 4), turn("left"), move("forward", 2)]),

    dict(mode="fix", title="Η πασχαλίτσα πηγαινοέρχεται! Περίμενε όσο πρέπει πριν περάσεις.",
         maps=["""
         T ~ ~ s ~ ~ T
         . ~ ~ s ~ ~ .
         S c . s . c G
         . ~ ~ s ~ ~ .
         T ~ ~ s ~ ~ T
         """], bug=[(3, 0), (3, 1), (3, 2), (3, 3), (3, 4)],
         program=[move("forward", 2), wait(3), move("forward", 4)], limit=3,
         solution=[move("forward", 2), wait(1), move("forward", 4)]),

    dict(mode="fix", title="Το R2 πήγε ανάποδα! Βρες την εντολή και διόρθωσέ τη.",
         maps=["""
         . . . . T .
         S . c . ~ ~
         ~ ~ ~ . ~ ~
         . . . . c G
         """],
         program=[move("forward", 3), turn("right"), move("back", 2), turn("left"), move("forward", 2)], limit=5,
         solution=[move("forward", 3), turn("right"), move("forward", 2), turn("left"), move("forward", 2)]),

    # Το πρώτο «Γράψε»: μία ευθεία, με μόνο το «Κινήσου» στις Εντολές (αλλάζει τον αριθμό για τα 3 αστέρια).
    dict(mode="write", title="Γράψε το πρόγραμμα: σύρε το «Κινήσου» κάτω από το «R2 starts»!",
         maps=["""
         T . . . . . T
         S . c . . . G
         ~ ~ ~ ~ ~ ~ ~
         """], palette=[move("forward", 1)], limit=1,
         solution=[move("forward", 6)]),

    dict(mode="write", title="Τώρα με μία στροφή: γράψε όλο το πρόγραμμα!",
         maps=["""
         T . . . .
         S . c . .
         ~ ~ ~ . ~
         . T ~ . T
         . . ~ G .
         """], palette=MOVE_TURN, limit=3,
         solution=[move("forward", 3), turn("right"), move("forward", 3)]),

    # ----------------------------------------------------------------- Γ'-Δ'
    # Οι γέφυρες βουλιάζουν 1 δευτερόλεπτο μετά το «Πάμε» και ανεβαίνουν ξανά στο 4ο (3 πάνω, 3 κάτω).
    # Χωρίς αναμονή το R2 φτάνει στην πρώτη τη στιγμή 3, όταν είναι κάτω. «περίμενε 1, 2 ή 3» στην αρχή: περνά
    # και τις δύο (η δεύτερη απέχει 6 δευτερόλεπτα, όσο ο κύκλος). Υπάρχει κι ένα κόλπο χωρίς «περίμενε»:
    # μισή στροφή (2 δευτερόλεπτα) και όλος ο δρόμος με την όπισθεν, πάλι με 6 εντολές.
    # Τα 3 αστέρια δίνονται ως 8 εντολές (ο δάσκαλος το ήθελε πιο εύκολο): π.χ. το «περίμενε» και στη μέση.
    dict(mode="write", title="Οι γέφυρες βουλιάζουν και ανεβαίνουν! Περίμενε την κατάλληλη στιγμή.",
         maps=["""
         T . . ~ . . .
         S . c = . # .
         ~ ~ ~ ~ . ~ ~
         . G c = . . T
         """], sink=(3, 3, 2), palette=MOVE_TURN + [wait(1)], limit=8,   # 6 το πιο σύντομο· 8 για να μην είναι δύσκολο
         solution=[wait(1), move("forward", 4), turn("right"), move("forward", 2), turn("right"),
                   move("forward", 3)]),

    dict(mode="fix", title="Το «επανάλαβε» κάνει τις εντολές πολλές φορές. Πόσες χρειάζονται;",
         maps=["""
         S . ~ ~ ~
         ~ c . ~ ~
         ~ ~ . . ~
         T ~ ~ G .
         """],
         program=[repeat(2, move("forward", 1), turn("right"), move("forward", 1), turn("left"))], limit=5,
         solution=[repeat(3, move("forward", 1), turn("right"), move("forward", 1), turn("left"))]),

    dict(mode="write", title="Ανέβα τη σκάλα με το «επανάλαβε»!",
         maps=["""
         . . T . G
         ~ ~ ~ . c
         ~ ~ . . ~
         ~ . c ~ ~
         S . ~ ~ T
         """], palette=MOVE_TURN + [repeat(10)], limit=5,
         solution=[repeat(4, move("forward", 1), turn("left"), move("forward", 1), turn("right"))]),

    dict(mode="write", title="Γύρω από τη λίμνη! Χρειάζονται μόνο 3 εντολές.",
         maps=["""
         T . . . . T
         . S . . c .
         . G ~ ~ . .
         . . ~ ~ . .
         . c . . c .
         T . . . . .
         """], palette=MOVE_TURN + [repeat(10)], limit=3,
         solution=[repeat(4, move("forward", 3), turn("right"))]),

    # ----------------------------------------------------------------- Ε'-ΣΤ'
    # Το R2 ακολουθεί μια εργαλειοθήκη που προχωρά και σταματά ακριβώς μετά τον φορτιστή. Με «< 15» φτάνει
    # δίπλα της, πάνω στον φορτιστή· με το λάθος «< 35» σταματά ένα κουτάκι νωρίτερα.
    dict(mode="fix", title="Το R2 ακολουθεί την εργαλειοθήκη, αλλά σταματά νωρίς! Βρες το λάθος.",
         maps=["""
         T . . . . . . . T
         S c c . . . G . .
         ~ ~ ~ ~ ~ ~ ~ ~ ~
         """], mover=[(3, 1), (4, 1), (5, 1), (6, 1), (7, 1)],
         program=[go(), until(35), stop()], limit=3,
         solution=[go(), until(15), stop()]),

    dict(mode="fix", title="Το R2 ψάχνει μόνο του τον δρόμο, αλλά κάτι δεν πάει καλά...",
         maps=["""
         S . c . . # ~
         ~ ~ ~ ~ . ~ ~
         ~ G c . . ~ ~
         ~ ~ ~ ~ # ~ ~
         ~ ~ ~ ~ ~ ~ ~
         """],
         program=[forever(if_else(15, [turn("left")], [move("forward", 1)]))], limit=4,
         solution=[forever(if_else(15, [turn("right")], [move("forward", 1)]))]),

    dict(mode="fix", title="Ο αισθητήρας μετράει πόσο μακριά είναι η πέτρα. Βρες τη λάθος εντολή!",
         maps=["""
         T . . . . . . T
         S c . . # . . .
         ~ ~ ~ G ~ ~ ~ ~
         """],
         program=[go(), until(35), stop(), turn("right"), move("forward", 1)], limit=5,
         solution=[go(), until(15), stop(), turn("right"), move("forward", 1)]),

    # Η μαύρη γραμμή (line): το «Ακολούθησε τη μαύρη γραμμή» την ακολουθεί μόνο του, με τις στροφές της.
    dict(mode="fix", title="Το R2 ξέρει να ακολουθεί τη μαύρη γραμμή! Βρες το λάθος.",
         maps=["""
         T . . . . . T
         S c . . ~ ~ .
         ~ ~ ~ . ~ ~ .
         . . . c . . G
         T ~ ~ ~ ~ ~ ~
         """], line=[(0, 1), (1, 1), (2, 1), (3, 1), (3, 2), (3, 3), (4, 3), (5, 3), (6, 3)],
         program=[follow("off")], limit=1,
         solution=[follow("on")]),

    # Το R2 ξεκινά πριν τη γραμμή: πάει πάνω της με «Κινήσου» και μετά την ακολουθεί ως τον φορτιστή
    # (στη γωνία στρίβει μόνο του). Αν ενεργοποιήσει το «Ακολούθησε» έξω από τη γραμμή, δεν ξέρει πού να πάει.
    dict(mode="write", title="Πήγαινε στη μαύρη γραμμή και μετά πες στο R2 να την ακολουθήσει!",
         maps=["""
         T . . . . . . T
         S . c . ~ ~ ~ T
         ~ ~ ~ . ~ ~ ~ ~
         T . . . . c . G
         ~ ~ ~ ~ ~ ~ ~ ~
         """], line=[(3, 1), (3, 2), (3, 3), (4, 3), (5, 3), (6, 3), (7, 3)],
         palette=[follow("on")] + MOVE_TURN, limit=3,
         solution=[move("forward", 3), follow("on")]),

    # Το τηλεκοντρόλ (keys): το χειριστήριο των πιστών «Δες», αλλά κάθε κουμπί τρέχει το πρόγραμμα «όταν πατηθεί
    # πλήκτρο» του βελακιού του (χωρίς «Πάμε»). Δίνεται μόνο το «μπροστά»: τα άλλα κουμπιά είναι γκρι ώσπου το
    # παιδί να φτιάξει τα προγράμματά τους. Ο χάρτης θέλει στροφή δεξιά και αριστερά και «πίσω» (κρύσταλλος σε
    # αδιέξοδο). drive: τα πατήματα με τα οποία το δοκιμάζουν οι έλεγχοι.
    dict(mode="write", keys=True, title="Τα γκρι κουμπιά δεν δουλεύουν! Φτιάξε τα προγράμματά τους.",
         maps=["""
         T . . . . . T
         S . . c ~ ~ T
         ~ ~ . ~ ~ ~ ~
         T . . . c G .
         ~ ~ ~ ~ ~ ~ ~
         """], drive=["up_arrow"] * 3 + ["down_arrow", "right_arrow", "up_arrow", "up_arrow", "left_arrow"]
                     + ["up_arrow"] * 3,
         palette=[key("up_arrow"), move("forward", 1), turn("right", 1)], limit=8,
         program=[key("up_arrow", move("forward", 1))],
         solution=[key("up_arrow", move("forward", 1)), key("down_arrow", move("back", 1)),
                   key("right_arrow", turn("right", 1)), key("left_arrow", turn("left", 1))]),

    dict(mode="write", title="Δύο πόρτες, δύο χρώματα! Άλλαξε το LED την κατάλληλη στιγμή.",
         maps=["""
         T # # . # # T
         S c R . B c G
         ~ ~ ~ ~ ~ ~ ~
         """], palette=[led("red")] + MOVE_TURN, limit=4,
         solution=[led("red"), move("forward", 3), led("blue"), move("forward", 3)]),
]
