class Slot:
    def __init__(self, sid, kind, step, anchor, mesh, screws=(), under=False, requires=(), self_screw=False):
        self.id, self.kind, self.step, self.anchor = sid, kind, step, anchor
        self.mesh = mesh                    # mesh(k): το κομμάτι στη θέση του (k: πόσο έχει βιδωθεί, για τα διαχωριστικά)
        self.screws = list(screws)          # [(είδος, άξονας, a, b, πού κάθεται, προς τα πού βγαίνει)]
        self.under = under                  # κάτω από τη βάση: φαίνεται μόνο με το ρομπότ ανάποδα
        self.requires = tuple(requires)     # θέσεις που πρέπει να έχουν γεμίσει πρώτα (μέσα στο ίδιο βήμα)
        self.self_screw = self_screw        # το ίδιο το κομμάτι βιδώνει (τα μικρά διαχωριστικά)


def _standoff_long(i):
    x, y = P.STANDOFFS[i]
    return Slot(f"so_long_{i}", "standoff_long", "1.1", (x, y, 62),
                lambda k=1.0: P.standoff(x, y, P.DECK_Z, P.BOARD_Z),
                screws=[("allen", "z", x, y, P.DECK_Z - 2, -1)])


def _standoff_short(i):
    x, y = P.STANDOFFS[i]

    def mesh(k=1.0):
        off = (1 - k) * 10
        return P.standoff(x, y, P.BOARD_TOP + off, P.SHORT_TOP + off, 2.6, phase=(1 - k) * 4)
    return Slot(f"so_short_{i}", "standoff_short", "5.2", (x, y, 92), mesh, self_screw=True)


